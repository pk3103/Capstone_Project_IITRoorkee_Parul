def generate_scr_narrative(findings: dict) -> dict:
    """Task 2 & 3: Generates SCR narrative using Google Gemini API with system instructions and strict parameter locking."""
    try:
        from google import genai
        from google.colab import userdata
        key = userdata.get('SY_API_KEY')
        if not key:
            raise ValueError("API key not found in userdata.")

        client = genai.Client(api_key=key)

        # System instruction fixing role, structure, and factual grounding constraint
        system_instruction = (
            "You are a senior data analyst writing for Mamaearth's regional ops and finance heads. "
            "You must structure your response under three exact labeled sections: Situation, Complication, Resolution. "
            "Strict Constraint: Every number in your output must come directly from the supplied findings dictionary "
            "and appear with the exact same value — do not invent or extrapolate statistics."
        )

        # User prompt interpolating from the findings dict (no hardcoded numbers)
        user_prompt = f"""
        Using the verified findings below, generate the SCR narrative:
        - Cleaned Total Revenue: ₹{findings['cleaned_total_revenue_inr']:,.2f}
        - Raw Total Revenue: ₹{findings['raw_total_revenue_inr']:,.2f}
        - Duplicate Reconciliation Delta: ₹{findings['duplicate_reconciliation_delta_inr']:,.2f}
        - Return Rates by Payment: {findings['return_rate_by_payment']}
        - Highest Risk Segment: COD in Tier-{findings['highest_risk_segment']['city_tier']} cities at {findings['highest_risk_segment']['return_rate_pct']}%
        - True Peak Month: {findings['true_peak_month']['month']} with ₹{findings['true_peak_month']['revenue_inr']:,.2f}
        - Outlier-Inflated Month: {findings['outlier_inflated_month']['month']} (Apparent: ₹{findings['outlier_inflated_month']['apparent_revenue_inr']:,.2f} vs Corrected: ₹{findings['outlier_inflated_month']['corrected_revenue_inr']:,.2f})
        """

        # Task 3: temperature=0.0 (deterministic factual report), max_output_tokens=400, timeout=15.0s
        response = client.models.generate_content(
            model='gemini-2.5-flash',
            contents=user_prompt,
            config={
                'system_instruction': system_instruction,
                'temperature': 0.0,
                'max_output_tokens': 400,
                'timeout': 15.0
            }
        )

        return {
            "status": "success",
            "narrative": response.text,
            "tokens": getattr(response.usage_metadata, 'total_token_count', 300)
        }

    except Exception as e:
        print(f"API call failed ({e}). Falling back to offline path.")
        return generate_scr_narrative_offline(findings)

def check_numeric_accuracy(narrative_text: str) -> bool:
    """Task 5: Checker function verifying all 5 required figures are present in the narrative text."""
    norm_text = narrative_text.replace(",", "")

    figures = [
        ("97358.30 or 97358.3", ["97358.30", "97358.3"]),
        ("44.4 (COD Return Rate)", ["44.4"]),
        ("54.5 (Highest Risk Segment)", ["54.5"]),
        ("2501.90 or 2501.9 (Delta)", ["2501.90", "2501.9"]),
        ("March & 20318.90 (True Peak)", ["March", "20318.90", "20318.9"])
    ]

    all_passed = True
    print("\n--- Numeric Accuracy Checklist ---")
    for label, options in figures:
        passed = any(opt in norm_text for opt in options)
        status = "PASS" if passed else "FAIL"
        print(f"[{status}] {label}")
        if not passed:
            all_passed = False

    return all_passed

