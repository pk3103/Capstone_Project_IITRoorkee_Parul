import os
import pandas as pd
import matplotlib.pyplot as plt
from IPython.display import Image, display

# Ensure output directory exists
os.makedirs("visualizations", exist_ok=True)

# 1. Load Data
orders = pd.read_csv('data/orders.csv')
customers = pd.read_csv('data/customers.csv')
products = pd.read_csv('data/products.csv')

# 2. Pipeline Preprocessing (Tasks 2–10)
orders['payment_method'] = orders['payment_method'].str.strip().str.upper()

dedup_subset = ['customer_id', 'product_id', 'order_date', 'quantity', 'discount_pct', 'payment_method', 'rating', 'returned']
orders_clean = orders.drop_duplicates(subset=dedup_subset, keep='first').copy()

orders_clean['discount_pct'] = orders_clean['discount_pct'].fillna(0)
orders_clean['rating'] = orders_clean['rating'].fillna(orders_clean['rating'].median())

merged = orders_clean.merge(products, on='product_id', how='left').merge(customers, on='customer_id', how='left')
merged['order_value'] = merged['quantity'] * merged['price'] * (1 - merged['discount_pct'] / 100.0)

# Flag IQR Outliers
q1 = merged['quantity'].quantile(0.25)
q3 = merged['quantity'].quantile(0.75)
iqr = q3 - q1
merged['is_outlier'] = (merged['quantity'] < (q1 - 1.5 * iqr)) | (merged['quantity'] > (q3 + 1.5 * iqr))

merged['order_date'] = pd.to_datetime(merged['order_date'])
merged['year_month'] = merged['order_date'].dt.to_period('M').astype(str)

# --- Visualization 1: Return Rate by Payment Method ---
plt.figure(figsize=(8, 5))
pm_returns = (merged.groupby('payment_method')['returned'].mean() * 100).sort_values(ascending=False)

bars = plt.bar(pm_returns.index, pm_returns.values, color=['#d9534f', '#5cb85c', '#0275d8'])
plt.title('COD Returns at 44.4% — 3x Card', fontsize=14, fontweight='bold', pad=15)
plt.xlabel('Payment Method', fontsize=11)
plt.ylabel('Return Rate (%)', fontsize=11)
plt.ylim(0, 60)

for bar in bars:
    yval = bar.get_height()
    plt.text(bar.get_x() + bar.get_width()/2.0, yval + 1.5, f'{yval:.1f}%', ha='center', va='bottom', fontweight='bold')

plt.tight_layout()
plt.savefig('visualizations/return_rate_by_payment.png', dpi=300)
plt.close()

# --- Visualization 2: Outlier-Corrected Monthly Revenue Trend ---
monthly_excl = merged[~merged['is_outlier']].groupby('year_month')['order_value'].sum()

plt.figure(figsize=(9, 5))
plt.plot(monthly_excl.index, monthly_excl.values, marker='o', linewidth=2.5, color='#0275d8')
plt.title('Outlier-Corrected Monthly Revenue Trend — March Peak Identified', fontsize=14, fontweight='bold', pad=15)
plt.xlabel('Month (2026)', fontsize=11)
plt.ylabel('Total Order Value (₹)', fontsize=11)
plt.grid(True, linestyle='--', alpha=0.6)

for x, y in zip(monthly_excl.index, monthly_excl.values):
    plt.annotate(f'₹{y:,.2f}', (x, y), textcoords="offset points", xytext=(0, 10), ha='center', fontsize=9, fontweight='bold')

plt.ylim(8000, 23000)
plt.tight_layout()
plt.savefig('visualizations/monthly_revenue_trend.png', dpi=300)
plt.close()

