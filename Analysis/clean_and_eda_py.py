# Task 9 — Correlation analysis
# 1. Compute correlation matrix across key numerical columns
corr_cols = ['rating', 'returned', 'discount_pct', 'quantity']
corr_matrix = merged[corr_cols].corr()

print("="*60)
print("Task 9 — Correlation Matrix")
print("="*60)
print(corr_matrix.round(4))

# 2. Define correlation strength mapping function based on taught bands
def get_strength_band(r):
    abs_r = abs(r)
    if abs_r <= 0.19:
        return "negligible"
    elif abs_r <= 0.39:
        return "weak"
    elif abs_r <= 0.69:
        return "moderate"
    else:
        return "strong"

# 3. Evaluate and display all 6 unique pairwise combinations
pairs = [
    ('rating', 'returned'),
    ('rating', 'discount_pct'),
    ('rating', 'quantity'),
    ('returned', 'discount_pct'),
    ('returned', 'quantity'),
    ('discount_pct', 'quantity')
]

print("\n" + "="*60)
print("Pairwise Correlation Evaluation")
print("="*60)
for col1, col2 in pairs:
    r_val = corr_matrix.loc[col1, col2]
    band = get_strength_band(r_val)
    print(f"• {col1} vs {col2}: r = {r_val:.4f} → {band} (|r| < 0.2)")

# 4. State hypothesis verdict
r_disc_ret = corr_matrix.loc['discount_pct', 'returned']
